const dictionaries: Record<Lang, Record<I18nKey, string>> = { zh, en };

export function t(lang: Lang, key: I18nKey): string {
  return dictionaries[lang][key] ?? key;
}

export function pick(lang: Lang, zhValue?: string | null, enValue?: string | null): string {
  if (lang === 'en' && enValue) {
    return enValue;
  }
  return zhValue ?? enValue ?? '';
}

export function localized(lang: Lang, row: Record<string, unknown>, key: string): string {
  if (lang === 'en') {
    const enValue = row[`${key}En`];
    if (typeof enValue === 'string' && enValue) {
      return enValue;
    }
  }
  const value = row[key];
  return typeof value === 'string' ? value : '';
}

export function fmtTime(lang: Lang, epoch: number): string {
  return new Date(epoch).toLocaleString(lang === 'zh' ? 'zh-CN' : 'en-US', {
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });
}

export function tenantName(lang: Lang, tenant: { nameZh: string; nameEn: string }): string {
  return lang === 'en' ? tenant.nameEn : tenant.nameZh;
}
